import React, {useEffect, useMemo, useState} from 'react';
import {Link, useSearchParams} from 'react-router-dom';
import {
    getPipelineEditorState,
    PipelineEditorDraft,
    PipelineEditorVersion,
    publishPipelineDraft,
    resetPipelineDraft,
    savePipelineDraft,
    validatePipelineDraft,
} from '../../services/api';
import './styles/pipeline_editor.css';

type EditorTab = 'overview' | 'compare' | 'reasoning' | 'history';
type DrawerPanel = 'inspector' | 'export' | null;

interface PipelineNode {
    id: string;
    title: string;
    kind: 'input' | 'operation' | 'output' | 'model';
    iri: string;
    status: 'stable' | 'draft' | 'warning';
    summary: string;
    rules: string[];
    impact: string;
}

